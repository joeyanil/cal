/** Writes docs/REMINDER_MESSAGES.md from the real wording in the code, so the
 *  document can never drift from what people actually see.
 *  Run: npx tsx scripts/gen-reminder-doc.ts */
import { writeFileSync } from 'fs'
import { buildReminderMessage, isoDate } from '../src/lib/calendar'
import type { ReminderAudience, ReminderTopic, ReminderDays } from '../src/lib/calendar'

const d = (s: string) => isoDate(s)
const AUD: [ReminderAudience, string][] = [
  ['STUDENT', 'Student'], ['GRADE_12_STUDENT', 'Grade 12 student'], ['TEACHER', 'Teacher'],
  ['HOMEROOM_TEACHER', 'Homeroom teacher'], ['GRADE_12_HOMEROOM_TEACHER', 'Grade 12 homeroom teacher'], ['OFFICE', 'Office team'],
]
const topics: [string, ReminderTopic][] = [
  ['School test', { topic: 'TEST', name: 'Semester 1 Final Exam', startDate: d('2027-01-18'), endDate: d('2027-01-22') }],
  ['Grade 12 national test', { topic: 'NATIONAL_TEST', startDate: d('2027-06-29'), endDate: d('2027-07-03') }],
  ['Start of each half of the year', { topic: 'HALF_START', halfName: 'Semester 2', date: d('2027-02-08') }],
  ['End of each half of the year', { topic: 'HALF_END', halfName: 'Semester 1', date: d('2027-01-29') }],
  ['The break begins', { topic: 'BREAK_START', date: d('2027-01-30'), resumeDate: d('2027-02-08') }],
  ['School resumes', { topic: 'SCHOOL_RESUMES', date: d('2027-02-08') }],
  ["Students' return day", { topic: 'STUDENTS_RETURN', date: d('2026-09-10') }],
  ['First day of the school year', { topic: 'YEAR_START', date: d('2026-09-14') }],
  ['Last day of the school year', { topic: 'YEAR_END', date: d('2027-07-07') }],
  ['Holiday on a school day', { topic: 'HOLIDAY', holidayKey: 'TIMKAT', name: 'Timkat (Epiphany)', date: d('2027-01-19'), closesSchoolDay: true }],
  ['Holiday before school starts', { topic: 'HOLIDAY', holidayKey: 'NEW_YEAR', name: 'Ethiopian New Year', date: d('2026-09-11'), closesSchoolDay: false }],
  ['Special day: sports day, students come', { topic: 'SPECIAL_DAY', situation: 'SPORTS_DAY', name: 'Sports Day', startDate: d('2027-03-05'), endDate: null, studentsCome: true }],
  ["Special day: teachers' training, students stay home", { topic: 'SPECIAL_DAY', situation: 'TEACHERS_TRAINING', name: "Teachers' training day", startDate: d('2027-03-05'), endDate: null, studentsCome: false }],
  ['A date has moved', { topic: 'DATE_MOVED', itemName: 'Semester 1 Final Exam', oldDate: d('2027-01-11'), newDate: d('2027-01-18') }],
]
const out: string[] = [
  '# Reminder messages (generated from the code)',
  '',
  'Sample dates are used. Every real message fills in its own dates. Do not edit this file by hand: run `npx tsx scripts/gen-reminder-doc.ts`.',
  '',
]
for (const [label, t] of topics) {
  out.push(`## ${label}`, '')
  for (const [a, name] of AUD) {
    const lines = ([30, 15, 5] as ReminderDays[]).map((n) => buildReminderMessage(a, t, n))
    if (lines.every((l) => l === null)) { out.push(`- **${name}:** gets nothing`); continue }
    const same = lines.every((l) => l?.body.replace(/\d+ days/g, 'N days') === lines[0]?.body.replace(/\d+ days/g, 'N days'))
    if (same) out.push(`- **${name}:** ${lines[1]!.body}`)
    else { out.push(`- **${name}:**`); ([30, 15, 5] as ReminderDays[]).forEach((n, i) => out.push(`  - ${n} days: ${lines[i]!.body}`)) }
  }
  out.push('')
}
writeFileSync('docs/REMINDER_MESSAGES.md', out.join('\n'))
console.log('written')
